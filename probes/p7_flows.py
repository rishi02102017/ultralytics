def case(name, fn):
    try:
        r = fn()
        print(f"[OK] {name}: {repr(r)[:300]}")
    except Exception as e:
        tb = traceback.extract_tb(e.__traceback__)[-1]
        print(f"[ERR] {name}: {type(e).__name__}: {str(e)[:300]} @ {tb.filename.split('site-packages/')[-1]}:{tb.lineno}")
td = Path(tempfile.mkdtemp()); os.chdir(td)
bus = cv2.imread(str(Path(ultralytics.__file__).parent / "assets" / "bus.jpg"))
vw = cv2.VideoWriter("v.mp4", cv2.VideoWriter_fourcc(*"mp4v"), 10, (640, 480))
for i in range(12):
    vw.write(cv2.resize(np.roll(bus, i * 10, axis=1), (640, 480)))
vw.release()
m = YOLO("yolo11n.pt")
P = lambda src, **k: [len(r.boxes) for r in m.predict(src, verbose=False, **k)]
case("video", lambda: P("v.mp4"))
case("video stride", lambda: P("v.mp4", vid_stride=5))
case("video save", lambda: (P("v.mp4", save=True, project=str(td / "r"), name="v", exist_ok=True), sorted(os.listdir(td / "r" / "v")))[1])
case("video save_frames", lambda: (P("v.mp4", save_frames=True, project=str(td / "r"), name="f", exist_ok=True), len(list((td / "r" / "f").rglob("*.jpg"))))[1])
case("video save_txt", lambda: (P("v.mp4", save_txt=True, project=str(td / "r"), name="t", exist_ok=True), sorted(p.name for p in (td / "r" / "t").rglob("*.txt"))[:20])[1])
case("video save_crop", lambda: (P("v.mp4", save_crop=True, project=str(td / "r"), name="c", exist_ok=True), len(list((td / "r" / "c").rglob("*.jpg"))))[1])
case("track video", lambda: [None if r.boxes.id is None else len(r.boxes.id) for r in m.track("v.mp4", verbose=False)])
case("track video stream save_txt", lambda: (list(m.track("v.mp4", verbose=False, stream=True, save_txt=True, project=str(td / "r"), name="tt", exist_ok=True)), sorted(p.name for p in (td / "r" / "tt").rglob("*.txt"))[:3], (td / "r" / "tt" / "labels" / "v_1.txt").read_text()[:200] if (td / "r" / "tt" / "labels" / "v_1.txt").exists() else None)[1:])
